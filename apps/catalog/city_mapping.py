def mahua_to_std(city_id):
    """麻花 cityId -> 国标码（无则返回 ''）。"""
    item = MAHUA_CITY_MAP.get(str(city_id))
    return item[1] if item else ''


def std_to_mahua(std_code):
    """国标码 -> 麻花 cityId（无则返回 None）。"""
    return STD_TO_MAHUA.get(str(std_code))


def city_name(city_id):
    """麻花 cityId -> 城市名。"""
    item = MAHUA_CITY_MAP.get(str(city_id))
    return item[0] if item else ''
